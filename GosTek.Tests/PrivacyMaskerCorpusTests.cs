    [Fact]
    public void CorpusMetrics_FalsePositivesLessThanThreePercent_And_FalseNegativesLessThanOnePercent()
    {
        // 1. ПРОВЕРКА ПОЛОЖИТЕЛЬНОГО КОРПУСА (False Negatives)
        int totalPositives = PositiveCorpus.Length;
        int falseNegatives = 0;

        foreach (var sample in PositiveCorpus)
        {
            var masked = PrivacyMasker.Mask(sample, out var extracted, numbered: true);
            bool hasMask = extracted.Count > 0 ||
                           masked.Contains("[ФИО") ||
                           masked.Contains("[ТЕЛЕФОН") ||
                           masked.Contains("[EMAIL") ||
                           masked.Contains("[ПАСПОРТ") ||
                           masked.Contains("[СЧЕТ") ||
                           masked.Contains("[УНП") ||
                           masked.Contains("[АДРЕС");

            if (!hasMask)
            {
                falseNegatives++;
            }
        }

        double falseNegativeRate = (double)falseNegatives / totalPositives;

        // 2. ПРОВЕРКА ОТРИЦАТЕЛЬНОГО КОРПУСА (False Positives)
        int totalNegatives = NegativeCorpus.Length;
        int falsePositives = 0;

        foreach (var sample in NegativeCorpus)
        {
            var masked = PrivacyMasker.Mask(sample, out var extracted, numbered: true);
            bool wasMasked = extracted.Count > 0 ||
                             masked.Contains("[ФИО") ||
                             masked.Contains("[ТЕЛЕФОН") ||
                             masked.Contains("[EMAIL") ||
                             masked.Contains("[ПАСПОРТ") ||
                             masked.Contains("[СЧЕТ") ||
                             masked.Contains("[УНП") ||
                             masked.Contains("[АДРЕС");

            if (wasMasked)
            {
                falsePositives++;
            }
        }

        double falsePositiveRate = (double)falsePositives / totalNegatives;

        // Итоговые замеры
        int totalCorpus = totalPositives + totalNegatives;
        Assert.True(totalCorpus >= 150, $"Размер корпуса должен быть >= 150 примеров, фактически: {totalCorpus}");

        // Жесткие критерии качества из ТЗ:
        // False Positives < 3%
        // False Negatives < 1%
        Assert.True(falseNegativeRate < 0.01,
            $"False Negatives должен быть < 1%, фактически: {falseNegativeRate:P2} ({falseNegatives}/{totalPositives})");

        Assert.True(falsePositiveRate < 0.03,
            $"False Positives должен быть < 3%, фактически: {falsePositiveRate:P2} ({falsePositives}/{totalNegatives})");
    }

